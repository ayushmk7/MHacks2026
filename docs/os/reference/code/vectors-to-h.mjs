// Turns vectors.json into vectors.h for the host tests. Run in this directory: node vectors-to-h.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const v = JSON.parse(readFileSync(new URL('./vectors.json', import.meta.url), 'utf8'));
const arr = h => h.match(/../g).map(x => '0x' + x).join(',');
let s = '/* generated by vectors.mjs + vectors-to-h.mjs from @solana/kit, sas-lib, @solana-program/token */\n';
s += `static const char *CURVE_HEX[] = {${v.curveVectors.map(c => `"${c.digest}"`).join(',')}};\n`;
s += `static const int CURVE_ON[] = {${v.curveVectors.map(c => (c.onCurve ? 1 : 0)).join(',')}};\n`;
s += `#define CURVE_N ${v.curveVectors.length}\n`;
const alt = v.tx.legacy_alt_order;
for (const [k, h] of Object.entries({
  PAYER: v.tx.payer_hex, SRC: v.tx.source_ata3_hex, DST: v.tx.dest_ata1_hex, DST_OWNER: v.tx.dest_owner_hex,
  MINT: v.tx.mint_hex, BH: v.tx.blockhash_hex, ATT: v.sas.attestation_hex, LEGACY: v.tx.legacy_1000.messageHex,
  V0: v.tx.v0_1000.messageHex, ACCT: v.attestationAccount.hex,
  CB_LEGACY: v.tx.legacy_compute_budget.messageHex, ALT_LEGACY: alt.messageHex, ALT_OWNER: alt.owner_hex, ALT_MINT: alt.mint_hex, ALT_SRC: alt.source_hex, ALT_DST: alt.dest_hex }))
  s += `static const uint8_t V_${k}[] = {${arr(h)}};\n`;
s += `static const char *B58_PAYER="${v.tx.payer}", *B58_CRED="${v.sas.credential}", *B58_SCHEMA="${v.sas.schema}", *B58_ATT="${v.sas.attestation_for_badge1}", *B58_OWNER1="${v.ata.owner1}", *B58_ATA1="${v.ata.ata1}", *B58_MINT="${v.ata.mint}";\n`;
writeFileSync(new URL('./vectors.h', import.meta.url), s);
